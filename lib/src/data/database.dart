/// Known schema versions. Add a new migration whenever tables
/// change and bump [AppDatabase.schemaVersion] — never destructive.
class DatabaseMigrations {
  DatabaseMigrations._();

  // Version history:
  // 1 — initial schema (products, movements, settings)
  //     NOTE: builds up to commit 35073b4 created these tables with drift's
  //     default plural names. 35073b4 overrode tableName to the singular form
  //     without adding a migration and without bumping schemaVersion, so two
  //     different physical schemas exist reporting user_version = 1. The
  //     upgrade path repairs the plural variant — see _renameLegacyTables.
  // 2 — enterprise schema (category, stockAuditSessions, stockAuditItems, batches)
  // 3 — supplier directory schema (suppliers table, product.supplierId, movement.supplierId)
  // 4 — batch.deletedAt (soft delete) + unique index on live product barcodes
  // 5 — indexes on the hot paths: movement.product_id / created_at / batch_id,
  //     product.name (live rows), stock_audit_item.session_id
  // 6 — locations: location table, movement.location_id, movement.transfer_ref
  // 7 — product.image_path (nullable, unwritten: the catalogue draws a
  //     tinted initial today, and the column is in place so adding photos
  //     later is a UI change rather than another migration) and
  //     product.is_favourite.
  static const int currentVersion = 7;

  /// Name given to the location that inherits all pre-existing stock.
  static const String defaultLocationName = 'Main';

  /// Tables renamed in 35073b4, oldest name first. Order matters: renaming
  /// `products` first lets SQLite rewrite the foreign key in `movements`
  /// before that table is itself renamed.
  static const Map<String, String> legacyTableNames = {
    'products': 'product',
    'movements': 'movement',
    'settings': 'setting',
  };
}

@DriftDatabase(
  tables: [Products, Movements, Settings, StockAuditSessions, StockAuditItems, Batches, Suppliers, Locations],
  daos: [ProductDao, MovementDao, SettingDao, AuditDao, BatchDao, SupplierDao, LocationDao],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor);

  AppDatabase.forTesting(super.executor);

  @override
  int get schemaVersion => DatabaseMigrations.currentVersion;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) async => m.createAll(),
    // One function per version transition, each typed against a *snapshot* of
    // the schema at its target version rather than against the live table
    // objects. That distinction matters: the previous implementation called
    // `m.addColumn(products, ...)`, which resolves to whatever `tableName` is
    // today — so renaming a table silently changed what an old migration did.
    // See `schema_versions.dart`, regenerated by `drift_dev schema steps`.
    onUpgrade: stepByStep(
      from1To2: (m, schema) async {
        // Must run before anything touches `product`/`movement`/`setting`:
        // a database created before 35073b4 still holds the plural names.
        await _renameLegacyTables();
        await m.addColumn(schema.product, schema.product.category);
        await m.addColumn(schema.movement, schema.movement.auditSessionId);
        await m.addColumn(schema.movement, schema.movement.batchId);
        await m.createTable(schema.stockAuditSession);
        await m.createTable(schema.stockAuditItem);
        await m.createTable(schema.batch);
      },
      from2To3: (m, schema) async {
        await m.createTable(schema.supplier);
        await m.addColumn(schema.product, schema.product.supplierId);
        await m.addColumn(schema.movement, schema.movement.supplierId);
      },
      from3To4: (m, schema) async {
        await m.addColumn(schema.batch, schema.batch.deletedAt);

        // The unique index cannot be created while duplicates exist, and a
        // user who imported the same CSV twice has them. Clear the barcode on
        // the newer copies rather than deleting rows — the duplicate still
        // holds real stock and a real ledger, so dropping it would be the data
        // loss this app exists to prevent. The user can re-enter the barcode
        // on whichever row is correct.
        await _clearDuplicateBarcodes();

        await m.create(schema.idxProductBarcodeLive);
      },
      from5To6: (m, schema) async {
        await m.createTable(schema.location);
        await m.addColumn(schema.movement, schema.movement.locationId);
        await m.addColumn(schema.movement, schema.movement.transferRef);
        await m.create(schema.idxMovementLocation);

        // Every existing movement happened somewhere. Backfilling them all to
        // one default location keeps every total identical before and after:
        // stock at Main == the old global stock, and the sum across locations
        // is unchanged. Nothing is recalculated and no row is rewritten
        // beyond gaining the column it was always implicitly part of.
        final now = DateTime.now();
        await into(locations).insert(
          LocationsCompanion.insert(
            name: DatabaseMigrations.defaultLocationName,
            isDefault: const Value(true),
            createdAt: now,
            updatedAt: now,
          ),
        );
        final defaultId = await customSelect(
          'SELECT id FROM location WHERE is_default = 1 LIMIT 1',
        ).getSingle().then((r) => r.read<int>('id'));

        await customStatement(
          'UPDATE movement SET location_id = ? WHERE location_id IS NULL',
          [defaultId],
        );
      },
      from4To5: (m, schema) async {
        // Indexes only — no column or table changes, so nothing can be lost.
        // The ledger is append-only and only grows, which is why these were
        // worth a migration of their own rather than waiting for the next
        // schema change.
        for (final index in [
          schema.idxMovementProduct,
          schema.idxMovementCreated,
          schema.idxMovementBatch,
          schema.idxProductNameLive,
          schema.idxAuditItemSession,
        ]) {
          await m.create(index);
        }
      },
      from6To7: (m, schema) async {
        // Two columns, neither of which needs a backfill. An existing row
        // has no photo, which is what NULL means, and is not a favourite,
        // which is what the column's default says.
        await m.addColumn(schema.product, schema.product.imagePath);
        await m.addColumn(schema.product, schema.product.isFavourite);
      },
    ),
    beforeOpen: (details) async {
      // Enforce FK constraints and keep the cache consistent on open.
      await customStatement('PRAGMA foreign_keys = ON');
      if (details.hadUpgrade) {
        await rebuildAllStockCaches();
      }
    },
  );

  /// Repairs databases created before commit 35073b4, which used drift's
  /// default plural table names. Renames each legacy table to its current
  /// name, but only when the legacy table is present and the current one is
  /// not — so a v1 database created after the rename is left untouched and
  /// an already-repaired database is never touched twice.
  ///
  /// This is a rename, never a drop: no row is read, written or deleted.
  Future<void> _renameLegacyTables() async {
    for (final entry in DatabaseMigrations.legacyTableNames.entries) {
      final hasLegacy = await _tableExists(entry.key);
      if (!hasLegacy) continue;

      final hasCurrent = await _tableExists(entry.value);
      if (hasCurrent) continue;

      await customStatement(
        'ALTER TABLE "${entry.key}" RENAME TO "${entry.value}"',
      );
    }
  }

  /// Keeps the barcode on the oldest live product holding it and clears it on
  /// the rest, so the partial unique index can be created. Returns how many
  /// rows were changed. Nothing is deleted.
  Future<int> _clearDuplicateBarcodes() async {
    final result = await customUpdate(
      '''
      UPDATE product SET barcode = NULL
      WHERE deleted_at IS NULL
        AND barcode IS NOT NULL
        AND id NOT IN (
          SELECT MIN(id) FROM product
          WHERE deleted_at IS NULL AND barcode IS NOT NULL
          GROUP BY barcode
        )
      ''',
      updates: {products},
    );
    return result;
  }

  Future<bool> _tableExists(String name) async {
    final rows = await customSelect(
      "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?1",
      variables: [Variable<String>(name)],
    ).get();
    return rows.isNotEmpty;
  }

  /// Recomputes every product's cached stockQty from the movement ledger.
  /// Callable from settings/debug and after any schema upgrade.
  Future<void> rebuildAllStockCaches() async {
    await _rebuildProductCaches();
    // Batch quantities are ledger-derived too, so they are repairable by the
    // same action. Before this, nothing could rebuild them and any drift was
    // permanent.
    await batchDao.rebuildAllBatchStocks();
  }

  Future<void> _rebuildProductCaches() async {
    await customStatement('''
      UPDATE product SET stock_qty = COALESCE(
        (SELECT SUM(qty_delta) FROM movement WHERE movement.product_id = product.id),
        0
      ) WHERE deleted_at IS NULL
    ''');
  }
}
